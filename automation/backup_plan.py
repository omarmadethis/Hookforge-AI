#!/usr/bin/env python3
"""D164 Backup plan: rank git-excluded assets by how hard they are to replace, for a private Drive folder named
"Hookforge Backup". This script only plans. Uploads go file by file through deliver.stage/verify_staged and
UploadFile, and each one is recorded in docs/backup_drive_index.json (which restore_assets.py --drive-index reads).
private/ and anything matching the sensitive patterns is never planned."""
import os, re, sys, json, subprocess, collections
R = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(R, "automation")); from restore_assets import SENSITIVE
TIERS = [  # (tier, label, path regex)
 (1, "irreplaceable refs (source/competitor reels, Omar's reference)", r"^refs/.*\.(mp4|mov|jpg|png)$"),
 (1, "audio library (songs the edits are cut to)", r"^music/(?!capcut_cache).*\.(m4a|mp3|wav)$"),
 (1, "final deliverables (approved cuts and captions)", r"^out/deliver/(?!manifest\.json$)(?!.*__)"),
 (2, "paid Higgsfield generations (credits spent, not free to regenerate)", r"^out/(live|pv_edit|pv_clips|purrventure_frames|purrventure_brand|trumpglow_product|trump_projector|patriotsglow|tg_v_say)/"),
 (2, "learning corpus / registries", r"^learning/(results/|audience_fit_log\.csv)"),
 (3, "emoji font (can be re-extracted, but slowly)", r"^assets/"),
 (3, "features DB + reel proxies (can be rebuilt from refs plus the pipeline)", r"^data/"),
]
SKIP = r"(__pycache__|\.pytest_cache|^\.cache/|^style/_work/|capcut_cache|^out/(dryrun|cast_audit|d75_grade|capcut_test|daily)/|\.lock$|\.pid$|\.log$|^analytics/|^engine/|^formats/|^tools/|^shared/|^voice/|^audience/)"

def plan():
    fs = [f for f in subprocess.run(["git", "ls-files", "-oi", "--exclude-standard", "-z"], cwd=R, capture_output=True).stdout.decode().split("\0") if f]
    items, skipped = [], collections.Counter()
    for f in fs:
        p = os.path.join(R, f)
        if not os.path.isfile(p): continue
        b = os.path.getsize(p)
        if SENSITIVE.search(f): skipped["sensitive/private (never)"] += b; continue
        if re.search(SKIP, f): skipped["cache / re-derivable / dry-run"] += b; continue
        t = next(((t, l) for t, l, rx in TIERS if re.search(rx, f)), None)
        if not t: skipped["unranked (small/misc, re-derivable)"] += b; continue
        items.append(dict(path=f, bytes=b, tier=t[0], group=t[1]))
    return sorted(items, key=lambda i: (i["tier"], i["group"], i["path"])), skipped

if __name__ == "__main__":
    items, skipped = plan(); g = collections.defaultdict(lambda: [0, 0, 0])
    for i in items: k = (i["tier"], i["group"]); g[k][0] += 1; g[k][1] += i["bytes"]
    gb = lambda b: f"{b/1e9:.2f} GB"
    L = ["# Backup plan: excluded assets to Drive \"Hookforge Backup\" (D164)", "Generated by automation/backup_plan.py. Ranked by how hard each asset is to replace. private/ and sensitive files are never uploaded.\n",
         "| tier | group | files | size | cumulative |", "|---|---|---|---|---|"]
    cum = 0
    for (t, l), (n, b, _) in sorted(g.items()): cum += b; L.append(f"| {t} | {l} | {n} | {gb(b)} | {gb(cum)} |")
    L += [f"\n**Total to back up: {gb(cum)}** ({len(items)} files). Not backed up:"] + [f"- {k}: {gb(v)}" for k, v in skipped.items()]
    json.dump(items, open(os.path.join(R, "learning", "backup_plan.json"), "w"), indent=0)
    open(os.path.join(R, "docs", "BACKUP_PLAN.md"), "w").write("\n".join(L) + "\n"); print("\n".join(L))
